"""Build the real Sheets-connected GitHub Pages frontend. Never reads a student DB."""
import argparse
import json
from pathlib import Path
import shutil

ROOT=Path(__file__).resolve().parents[1]

def build(endpoint):
    destination=ROOT/'docs'
    shutil.copytree(ROOT/'public',destination,dirs_exist_ok=True)
    html=(destination/'index.html').read_text(encoding='utf-8')
    for old,new in [('href="/style.css"','href="./style.css"'),('src="/app.js"','src="./app.js"'),('href="/"','href="./"')]:
        html=html.replace(old,new)
    html=html.replace('<script src="./app.js"','<script src="./config.js" defer></script><script src="./cloud-transport.js" defer></script><script src="./app.js"')
    html=html.replace('로컬 개발 버전 · 기록은 서버 PC에 저장됩니다','구글 시트 연결 · 학생별 활동 기록 누적')
    (destination/'index.html').write_text(html,encoding='utf-8')
    css=(destination/'style.css').read_text(encoding='utf-8').replace('url("/fonts/','url("./fonts/')
    (destination/'style.css').write_text(css,encoding='utf-8')
    (destination/'config.js').write_text('window.MILKY_CONFIG = '+json.dumps({'mode':'sheets','appsScriptUrl':endpoint},ensure_ascii=False)+';\n',encoding='utf-8')
    (destination/'.nojekyll').touch()
    # Remove only the known files generated by the abandoned preview builder.
    for name in ('preview.js','demo-tasks.json'):
        file=destination/name
        if file.is_file():file.unlink()
    print('Built Sheets-connected Pages frontend; '+('deployment endpoint configured.' if endpoint else 'Google deployment endpoint is still required.'))

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--endpoint',default='');args=parser.parse_args();build(args.endpoint)
